import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { randomInt } from 'node:crypto';
import { setDefaultResultOrder } from 'node:dns';

setDefaultResultOrder('ipv4first');
const origin = new URL(process.argv[2] || 'https://preview.exbeam.com').origin;
const healthResponse = await fetch(origin + '/api/health', { cache: 'no-store', signal: AbortSignal.timeout(30000) });
assert.equal(healthResponse.status, 200);
assert.match(healthResponse.headers.get('content-type') || '', /application\/json/, 'Never create test families on a legacy HTML fallback.');
const health = await healthResponse.json();
assert.equal(health.ok, true);
assert.equal(health.database?.connected, true);
assert.ok(health.release, 'Verify the deployed Worker before any test write.');
const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const code = 'QA' + Array.from({ length: 6 }, () => alphabet[randomInt(alphabet.length)]).join('');
const pin = String(randomInt(100000, 999999));
const date = new Date().toISOString().slice(0, 10);
const report = { origin, checkedAt: new Date().toISOString(), checks: [], workspaceCode: code };
const request = async (payload, expected = 200) => {
  const response = await fetch(origin + '/api/summer-workspace', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ code, ...payload }), signal: AbortSignal.timeout(30000) });
  const body = await response.json();
  assert.equal(response.status, expected, `Unexpected family API status ${response.status}: ${body.code || ''}`);
  assert.ok(!JSON.stringify(body).includes('pin_hash') && !JSON.stringify(body).includes('pinHash'));
  return body;
};
const created = await request({ action: 'create', pin, state: { schemaVersion: 1, childName: 'Cloudflare migration QA' } }, 201);
assert.equal(created.state.childName, 'Cloudflare migration QA');
report.checks.push('Created a new isolated family in D1, with no PIN hash in its response');
await request({ action: 'verify', pin });
await request({ action: 'verify', pin: 'wrong' }, 403);
report.checks.push('Parent PIN accepted; incorrect PIN rejected');
const tasks = created.state.tasks.filter(task => task.kind !== 'quiz').slice(0, 2);
assert.equal(tasks.length, 2);
const mutations = tasks.map((task, index) => ({ id: `migration-qa-${Date.now()}-${index}`, type: 'complete-task', date, taskId: task.id }));
await Promise.all(mutations.map(mutation => request({ action: 'mutate', role: 'child', mutation })));
const read = async () => {
  const response = await fetch(`${origin}/api/summer-workspace?code=${code}`, { cache: 'no-store', signal: AbortSignal.timeout(30000) });
  assert.equal(response.status, 200); return response.json();
};
const after = await read();
assert.ok(tasks.every(task => after.state.days[date].completedTaskIds.includes(task.id)));
report.checks.push('Two independent concurrent requests preserve both completions');
const balance = after.state.sun;
await request({ action: 'mutate', role: 'child', mutation: mutations[0] });
assert.equal((await read()).state.sun, balance);
report.checks.push('Retrying an already committed action cannot grant sunlight twice');
await request({ action: 'mutate', role: 'child', mutation: { id: 'forbidden-config', type: 'save-config', date, childName: 'forbidden' } }, 403);
report.checks.push('Child configuration changes are denied');
await request({ action: 'mutate', role: 'parent', pin, mutation: { id: `parent-${Date.now()}`, type: 'save-config', date, childName: 'Cloudflare migration QA', tasks: created.state.tasks, vacationStart: created.state.vacationStart, vacationEnd: created.state.vacationEnd } });
report.checks.push('Parent configuration persists using the original API protocol');
await fs.mkdir('.migration.local', { recursive: true, mode: 0o700 });
const record = `.migration.local/family-${new URL(origin).hostname}.json`;
await fs.writeFile(record, JSON.stringify(report, null, 2), { mode: 0o600 });
console.log(JSON.stringify({ origin, checks: report.checks.length, passed: true, privateRecord: record }));
